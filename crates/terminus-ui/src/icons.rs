//! Lucide icon geometry.
//!
//! Rio's `sugarloaf` exposes filled primitives only (`rect`, `line`,
//! `arc`, `polygon`) — there is no SVG renderer (its `components::svg`
//! module is commented out). So the icons are kept here as the exact
//! stroke geometry of the real [Lucide](https://lucide.dev) sources,
//! pre-decomposed: each icon's `d`/`rect`/`line` markup was converted
//! offline into the 2px-wide line segments and circular arcs its stroke
//! covers, on Lucide's 24x24 grid. No path is hand-drawn and no icon is
//! faked with a Unicode glyph.
//!
//! `Seg::*` coordinates are on that 24x24 grid; [`IconPlacement`] maps
//! them onto the window and scales the 2px stroke along with them.

/// One stroke of an icon, on Lucide's 24x24 grid.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Seg {
    Line {
        x1: f32,
        y1: f32,
        x2: f32,
        y2: f32,
    },
    /// A stroked circular arc: the stroke follows the circle of radius
    /// `r` around `(cx, cy)` from `start_deg` to `end_deg`.
    ///
    /// Angles are screen-space: 0 is +x (right) and 90 is +y (down),
    /// matching `sugarloaf`'s `arc`. A stroke is direction-agnostic, so
    /// `start_deg` is always the smaller angle and `end_deg` may exceed
    /// 360.
    Arc {
        cx: f32,
        cy: f32,
        r: f32,
        start_deg: f32,
        end_deg: f32,
    },
}

/// Lucide draws every icon in this box.
pub const LUCIDE_GRID: f32 = 24.0;
/// Lucide's default stroke width, in grid units.
pub const LUCIDE_STROKE: f32 = 2.0;

/// The icons the chrome paints.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Icon {
    /// `server` — the Hosts section.
    Server,
    /// `arrow-right-left` — the Port forwards section.
    ArrowRightLeft,
    /// `folder` — the SFTP section.
    Folder,
    /// `sliders-horizontal` — the Settings section.
    SlidersHorizontal,
    /// `plus` — the add-host affordance.
    Plus,
}

impl Icon {
    /// The stroke segments, verbatim from the Lucide source of that name.
    pub fn segments(self) -> &'static [Seg] {
        match self {
            Icon::Server => SERVER,
            Icon::ArrowRightLeft => ARROW_RIGHT_LEFT,
            Icon::Folder => FOLDER,
            Icon::SlidersHorizontal => SLIDERS_HORIZONTAL,
            Icon::Plus => PLUS,
        }
    }
}

/// Where an icon is being drawn, and at what size.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct IconPlacement {
    /// Top-left corner of the icon box, in logical pixels.
    pub x: f32,
    pub y: f32,
    /// Side of the (square) icon box, in logical pixels.
    pub size: f32,
}

impl IconPlacement {
    pub const fn new(x: f32, y: f32, size: f32) -> Self {
        Self { x, y, size }
    }

    /// Grid units -> logical pixels.
    pub fn scale(&self) -> f32 {
        self.size / LUCIDE_GRID
    }

    /// Stroke width in logical pixels.
    pub fn stroke(&self) -> f32 {
        LUCIDE_STROKE * self.scale()
    }

    /// Map a grid point onto the window.
    pub fn map(&self, gx: f32, gy: f32) -> (f32, f32) {
        let s = self.scale();
        (self.x + gx * s, self.y + gy * s)
    }
}

